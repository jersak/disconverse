export type IconName = keyof typeof PATHS;

export function Icon({ name, size = 20, slashed = false }: { name: IconName; size?: number; slashed?: boolean }) {
  return (
    <svg width={size} height={size} viewBox="0 0 24 24" aria-hidden="true" className="icon">
      <path fill="currentColor" d={PATHS[name]} />
      {slashed && <line x1="3" y1="3" x2="21" y2="21" stroke="var(--red)" strokeWidth="2.5" strokeLinecap="round" />}
    </svg>
  );
}

const AVATAR_COLORS = ["#5865f2", "#3ba55c", "#faa61a", "#ed4245", "#eb459e", "#00a8fc", "#9b59b6", "#e67e22"];

export function Avatar({
  userId,
  name,
  avatarUrl = null,
  size = 32,
  speaking = false,
}: {
  userId: number;
  name: string;
  avatarUrl?: string | null;
  size?: number;
  speaking?: boolean;
}) {
  if (avatarUrl) {
    return (
      <img
        className={`avatar avatar-img${speaking ? " speaking" : ""}`}
        src={avatarUrl}
        alt=""
        width={size}
        height={size}
        style={{ width: size, height: size }}
      />
    );
  }
  return (
    <span
      className={`avatar${speaking ? " speaking" : ""}`}
      style={{
        width: size,
        height: size,
        fontSize: size * 0.45,
        background: AVATAR_COLORS[Math.abs(userId) % AVATAR_COLORS.length],
      }}
    >
      {name.slice(0, 1).toUpperCase()}
    </span>
  );
}

const timeFormat = new Intl.DateTimeFormat(undefined, { hour: "numeric", minute: "2-digit" });
const dateFormat = new Intl.DateTimeFormat(undefined, { year: "numeric", month: "2-digit", day: "2-digit" });

export function formatTimestamp(ts: number): string {
  const d = new Date(ts);
  const today = new Date();
  const yesterday = new Date(today);
  yesterday.setDate(today.getDate() - 1);
  const time = timeFormat.format(d);
  if (d.toDateString() === today.toDateString()) return `Today at ${time}`;
  if (d.toDateString() === yesterday.toDateString()) return `Yesterday at ${time}`;
  return `${dateFormat.format(d)} ${time}`;
}

export const formatTime = (ts: number) => timeFormat.format(new Date(ts));
